//! .NET's `char` classification, as agg-sharp's Markdown writer sees it
//! (`char.IsPunctuation || char.IsSymbol`, `char.IsLetter`,
//! `char.IsLetterOrDigit`).  Used by [`super::escaping`] and
//! [`super::inline_writer`] to decide escapes and delimiter flanking exactly
//! as agg-sharp does.
//!
//! .NET classifies UTF-16 code units, so a character outside the Basic
//! Multilingual Plane (an emoji, say) is two surrogates, each in category Cs:
//! never a letter, digit, punctuation or symbol.  These functions answer the
//! same for every such character.  The tables are generated from the Unicode
//! Character Database (Unicode 16.0, Python's `unicodedata`), Basic
//! Multilingual Plane only, sorted and non-overlapping.

/// True for punctuation or symbols (general categories P* and S*).
pub(crate) fn is_punctuation_or_symbol(c: char) -> bool {
    in_table(PUNCTUATION_OR_SYMBOL, c)
}

/// True for letters (general categories L*).
pub(crate) fn is_letter(c: char) -> bool {
    in_table(LETTER, c)
}

/// True for letters (L*) and decimal digits (Nd).
pub(crate) fn is_letter_or_digit(c: char) -> bool {
    in_table(LETTER_OR_DIGIT, c)
}

fn in_table(table: &[(u16, u16)], c: char) -> bool {
    let Ok(unit) = u16::try_from(u32::from(c)) else {
        // Outside the BMP: .NET sees two surrogates, which belong to no class.
        return false;
    };
    table
        .binary_search_by(|&(low, high)| {
            if high < unit {
                std::cmp::Ordering::Less
            } else if low > unit {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

